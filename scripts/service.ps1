# Keeps laya-serve running for fast-laya-plugin on Windows: starts it at every
# login and restarts it when it dies. A small supervisor script, kept in
# %LOCALAPPDATA%\fast-laya-plugin, runs laya-serve in a loop; an entry under
# HKCU\...\Run starts the supervisor at login. No administrator rights needed.
#
# usage: service.ps1 install|start|uninstall|status
#
#   install    write the supervisor and the Run entry and start it; does
#              nothing when it is already installed with the same settings
#   start      start the supervisor now (no-op when it is running)
#   uninstall  stop it and remove the Run entry and the supervisor
#   status     say whether it is installed and running
#
# env: LAYA_HOST (127.0.0.1), LAYA_PORT (8000), LAYA_MODELS (english),
#      LAYA_SERVE (laya-serve: a name on PATH or an absolute path)
param(
    [Parameter(Position = 0)]
    [ValidateSet('install', 'start', 'uninstall', 'status')]
    [string]$Action = 'install'
)

$ErrorActionPreference = 'Stop'
$Name = 'fast-laya-serve'
$Dir = Join-Path $env:LOCALAPPDATA 'fast-laya-plugin'
$Supervisor = Join-Path $Dir 'laya-supervise.ps1'
$Log = Join-Path $Dir 'laya-serve.log'
$RunKey = 'HKCU:\Software\Microsoft\Windows\CurrentVersion\Run'

function Setting([string]$Variable, [string]$Default) {
    $value = [Environment]::GetEnvironmentVariable($Variable)
    if ($value) { $value } else { $Default }
}

function Quote([string]$Text) { "'" + $Text.Replace("'", "''") + "'" }

# Absolute path of laya-serve; the login session does not see this shell's PATH.
function Resolve-LayaServe {
    $cmd = Setting 'LAYA_SERVE' 'laya-serve'
    if ([IO.Path]::IsPathRooted($cmd)) {
        if (Test-Path $cmd) { return $cmd }
    } else {
        $found = Get-Command $cmd -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1
        if ($found) { return $found.Source }
        $local = Join-Path $HOME ".local\bin\$cmd.exe"
        if (Test-Path $local) { return $local }
    }
    throw "$cmd not found. Install it with: uv tool install `"laya[serve]`""
}

function Supervisor-Text([string]$Exe) {
    $lines = @(
        '# Generated by fast-laya-plugin (scripts/service.ps1). Restarts laya-serve when it exits.',
        '$ErrorActionPreference = ''Continue''',
        '$created = $false',
        "`$mutex = [System.Threading.Mutex]::new(`$true, 'Local\$Name', [ref]`$created)",
        'if (-not $created) { exit 0 }',
        "`$env:LAYA_HOST = $(Quote (Setting 'LAYA_HOST' '127.0.0.1'))",
        "`$env:LAYA_PORT = $(Quote (Setting 'LAYA_PORT' '8000'))",
        "`$env:LAYA_MODELS = $(Quote (Setting 'LAYA_MODELS' 'english'))",
        'while ($true) {',
        "    & $(Quote $Exe) *> $(Quote $Log)",
        '    Start-Sleep -Seconds 10',
        '}'
    )
    ($lines -join "`r`n") + "`r`n"
}

$RunCommand = "powershell.exe -NoProfile -WindowStyle Hidden -ExecutionPolicy Bypass -File `"$Supervisor`""

function Get-Supervisors {
    Get-CimInstance Win32_Process -Filter "Name = 'powershell.exe'" |
        Where-Object { $_.CommandLine -and $_.CommandLine.Contains($Supervisor) }
}

function Stop-Supervisor {
    foreach ($process in @(Get-Supervisors)) {
        & taskkill.exe /PID $process.ProcessId /T /F *> $null
    }
}

function Start-Supervisor {
    Start-Process powershell.exe -WindowStyle Hidden -ArgumentList @(
        '-NoProfile', '-WindowStyle', 'Hidden', '-ExecutionPolicy', 'Bypass', '-File', "`"$Supervisor`""
    )
}

function Get-RunEntry {
    (Get-ItemProperty -Path $RunKey -Name $Name -ErrorAction SilentlyContinue).$Name
}

switch ($Action) {
    'install' {
        $text = Supervisor-Text (Resolve-LayaServe)
        $current = if (Test-Path $Supervisor) { Get-Content -Raw $Supervisor } else { $null }
        if ($current -eq $text -and (Get-RunEntry) -eq $RunCommand) {
            Start-Supervisor
            Write-Output "unchanged: $Supervisor"
            break
        }
        New-Item -ItemType Directory -Force -Path $Dir | Out-Null
        [IO.File]::WriteAllText($Supervisor, $text)
        Set-ItemProperty -Path $RunKey -Name $Name -Value $RunCommand
        Stop-Supervisor
        Start-Supervisor
        Write-Output "installed: $Supervisor"
    }
    'start' {
        if (-not (Test-Path $Supervisor)) { throw "not installed: $Supervisor" }
        Start-Supervisor
        Write-Output "started: $Name"
    }
    'uninstall' {
        Remove-ItemProperty -Path $RunKey -Name $Name -ErrorAction SilentlyContinue
        Stop-Supervisor
        Remove-Item -Force -ErrorAction SilentlyContinue $Supervisor
        Write-Output "removed: $Supervisor"
    }
    'status' {
        if (-not (Get-RunEntry)) { Write-Output 'not installed'; break }
        $state = if (@(Get-Supervisors).Count -gt 0) { 'running' } else { 'not running' }
        Write-Output "installed: $Supervisor ($state)"
    }
}
