#!/usr/bin/env sh
# Keeps laya-serve running for fast-laya-plugin: starts it at every login and
# restarts it when it dies. A systemd user service on Linux, a LaunchAgent on
# macOS; under Git Bash, MSYS or Cygwin it hands over to service.ps1.
#
# usage: service.sh install|start|uninstall|status
#
#   install    write the service and start it; does nothing when it is already
#              installed with the same settings (safe to run at every session)
#   start      start the installed service now (no-op when it is running)
#   uninstall  stop the service and remove it
#   status     say whether it is installed and running
#
# env: LAYA_HOST (127.0.0.1), LAYA_PORT (8000), LAYA_MODELS (english),
#      LAYA_SERVE (laya-serve: a name on PATH or an absolute path)
#
# exit: 0 ok, 1 error, 3 no supported service manager here
set -eu

ACTION="${1:-install}"
NAME="fast-laya-serve"
LABEL="com.fast-laya-plugin.laya-serve"
HOST="${LAYA_HOST:-127.0.0.1}"
PORT="${LAYA_PORT:-8000}"
MODELS="${LAYA_MODELS:-english}"

fail() { printf 'error: %s\n' "$1" >&2; exit 1; }
unsupported() { printf 'unsupported: %s\n' "$1" >&2; exit 3; }

# Absolute path of laya-serve; services do not see the login shell's PATH.
resolve_laya_serve() {
  cmd="${LAYA_SERVE:-laya-serve}"
  case "$cmd" in
    /*)
      [ -x "$cmd" ] && { printf '%s\n' "$cmd"; return; } ;;
    *)
      found="$(command -v "$cmd" 2>/dev/null || true)"
      case "$found" in /*) printf '%s\n' "$found"; return ;; esac
      [ -x "$HOME/.local/bin/$cmd" ] && { printf '%s\n' "$HOME/.local/bin/$cmd"; return; } ;;
  esac
  fail "$cmd not found. Install it with: uv tool install \"laya[serve]\""
}

# ---- Linux: systemd user service ------------------------------------------

UNIT_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user"
UNIT="$UNIT_DIR/$NAME.service"

systemd_available() {
  command -v systemctl >/dev/null 2>&1 && systemctl --user show-environment >/dev/null 2>&1
}

linux_unit() {
  cat <<EOF
# Generated by fast-laya-plugin (scripts/service.sh).
[Unit]
Description=laya-serve for fast-laya-plugin
StartLimitIntervalSec=0

[Service]
Environment=LAYA_HOST=$HOST
Environment=LAYA_PORT=$PORT
Environment=LAYA_MODELS=$MODELS
ExecStart="$1"
Restart=always
RestartSec=10

[Install]
WantedBy=default.target
EOF
}

linux() {
  case "$ACTION" in
    install)
      systemd_available || unsupported "no systemd user session"
      unit="$(linux_unit "$(resolve_laya_serve)")"
      if [ -f "$UNIT" ] && [ "$(cat "$UNIT")" = "$unit" ] && systemctl --user is-enabled --quiet "$NAME"; then
        systemctl --user start "$NAME"
        echo "unchanged: $UNIT"
        return
      fi
      mkdir -p "$UNIT_DIR"
      printf '%s\n' "$unit" >"$UNIT"
      systemctl --user daemon-reload
      systemctl --user enable "$NAME" >/dev/null 2>&1
      systemctl --user restart "$NAME"
      echo "installed: $UNIT"
      ;;
    start)
      systemd_available || unsupported "no systemd user session"
      [ -f "$UNIT" ] || fail "not installed: $UNIT"
      systemctl --user start "$NAME"
      echo "started: $NAME"
      ;;
    uninstall)
      if systemd_available; then
        systemctl --user disable --now "$NAME" >/dev/null 2>&1 || true
      fi
      rm -f "$UNIT"
      if systemd_available; then systemctl --user daemon-reload; fi
      echo "removed: $UNIT"
      ;;
    status)
      if [ ! -f "$UNIT" ]; then echo "not installed"; return; fi
      state="unknown"
      if systemd_available; then state="$(systemctl --user is-active "$NAME" 2>/dev/null || true)"; fi
      echo "installed: $UNIT ($state)"
      ;;
    *) fail "unknown action: $ACTION (install, start, uninstall, status)" ;;
  esac
}

# ---- macOS: LaunchAgent ---------------------------------------------------

PLIST="$HOME/Library/LaunchAgents/$LABEL.plist"
MAC_LOG="$HOME/Library/Logs/$NAME.log"
DOMAIN="gui/$(id -u)"

xml() { printf '%s' "$1" | sed -e 's/&/\&amp;/g' -e 's/</\&lt;/g' -e 's/>/\&gt;/g'; }

mac_plist() {
  cat <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by fast-laya-plugin (scripts/service.sh). -->
<plist version="1.0">
<dict>
  <key>Label</key><string>$LABEL</string>
  <key>ProgramArguments</key><array><string>$(xml "$1")</string></array>
  <key>EnvironmentVariables</key>
  <dict>
    <key>LAYA_HOST</key><string>$(xml "$HOST")</string>
    <key>LAYA_PORT</key><string>$(xml "$PORT")</string>
    <key>LAYA_MODELS</key><string>$(xml "$MODELS")</string>
  </dict>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><true/>
  <key>ThrottleInterval</key><integer>10</integer>
  <key>StandardOutPath</key><string>$(xml "$MAC_LOG")</string>
  <key>StandardErrorPath</key><string>$(xml "$MAC_LOG")</string>
</dict>
</plist>
EOF
}

mac_loaded() { launchctl print "$DOMAIN/$LABEL" >/dev/null 2>&1; }

mac() {
  case "$ACTION" in
    install)
      plist="$(mac_plist "$(resolve_laya_serve)")"
      if [ -f "$PLIST" ] && [ "$(cat "$PLIST")" = "$plist" ] && mac_loaded; then
        echo "unchanged: $PLIST"
        return
      fi
      mkdir -p "$(dirname "$PLIST")" "$(dirname "$MAC_LOG")"
      printf '%s\n' "$plist" >"$PLIST"
      launchctl bootout "$DOMAIN/$LABEL" >/dev/null 2>&1 || true
      launchctl enable "$DOMAIN/$LABEL" >/dev/null 2>&1 || true
      launchctl bootstrap "$DOMAIN" "$PLIST"
      echo "installed: $PLIST"
      ;;
    start)
      [ -f "$PLIST" ] || fail "not installed: $PLIST"
      mac_loaded || launchctl bootstrap "$DOMAIN" "$PLIST"
      launchctl kickstart "$DOMAIN/$LABEL"
      echo "started: $LABEL"
      ;;
    uninstall)
      launchctl bootout "$DOMAIN/$LABEL" >/dev/null 2>&1 || true
      rm -f "$PLIST"
      echo "removed: $PLIST"
      ;;
    status)
      if [ ! -f "$PLIST" ]; then echo "not installed"; return; fi
      if mac_loaded; then echo "installed: $PLIST (loaded)"; else echo "installed: $PLIST (not loaded)"; fi
      ;;
    *) fail "unknown action: $ACTION (install, start, uninstall, status)" ;;
  esac
}

# ---------------------------------------------------------------------------

case "$(uname -s)" in
  Linux) linux ;;
  Darwin) mac ;;
  MINGW* | MSYS* | CYGWIN*)
    script="$(dirname "$0")/service.ps1"
    command -v cygpath >/dev/null 2>&1 && script="$(cygpath -w "$script")"
    exec powershell.exe -NoProfile -NonInteractive -ExecutionPolicy Bypass -File "$script" "$ACTION"
    ;;
  *) unsupported "$(uname -s)" ;;
esac
